// Builds js/data.js from the SERA data files so the app runs from file:// with no server.
// Usage: node tools/build-data.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, "..", "..", "uix", "sera-apply-assets", "sera-apply-assets", "data");
const out = join(here, "..", "js", "data.js");

// The data files contain no quoted fields, so a plain split is safe.
function readCsv(file) {
  const [head, ...rows] = readFileSync(join(src, file), "utf8").trim().split(/\r?\n/);
  const keys = head.split(",");
  return rows.map((line) => {
    const cells = line.split(",");
    return Object.fromEntries(keys.map((k, i) => [k, (cells[i] ?? "").trim()]));
  });
}

const TYPE_LABEL = {
  university: "University",
  university_college_or_campus: "University college / campus",
  non_university_institution: "Other degree-awarding institution",
  registered_not_admitting: "Registered, not admitting in 2026/27",
};

const slug = (s) => s.toLowerCase().replace(/\(.*?\)/g, "").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

const seen = new Set();
const institutions = readCsv("institutions_2026_27.csv").map((r) => {
  let id = slug(r.short_name || r.name);
  while (seen.has(id)) id += "-2";
  seen.add(id);
  const region = r.location.replace(/\s*\(.*\)/, "").trim();
  return {
    id,
    name: r.name,
    short: r.short_name || "",
    type: r.type,
    typeLabel: TYPE_LABEL[r.type] || r.type,
    location: r.location,
    region,
    ownership: r.ownership || "",
    admits: r.admits_form_six_2026_27 === "1",
  };
});

const schools = readCsv("acsee_schools.csv").map((r) => ({
  index: r.index_no,
  name: r.name,
  y2025: r.acsee_2025 === "1",
  y2026: r.acsee_2026 === "1",
}));

const scholarships = JSON.parse(readFileSync(join(src, "scholarships.json"), "utf8"));
const rules = JSON.parse(readFileSync(join(src, "brand_and_rules.json"), "utf8"));

const data = { builtAt: new Date().toISOString().slice(0, 10), institutions, schools, scholarships, rules };
writeFileSync(out, "/* Generated by tools/build-data.mjs. Do not edit by hand. */\nwindow.SERA_DATA = " + JSON.stringify(data) + ";\n");
console.log(`institutions ${institutions.length}, schools ${schools.length}, scholarships ${scholarships.length} -> ${out}`);
